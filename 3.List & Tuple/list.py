#list in python
#list is a collection of items which are ordered and changeable. It allows duplicate members.

marks = [90, 80.0, 70, 60.65, 50]
print(marks) #prints the whole list
print(type(marks[0])) #prints the type of the first element of the list
print(type(marks[1])) #prints the type of the second element of the list
print(type(marks[2])) #prints the type of the third element of the list
print(type(marks[3])) #prints the type of the fourth element of the list
print(type(marks[4])) #prints the type of the fifth element of the list



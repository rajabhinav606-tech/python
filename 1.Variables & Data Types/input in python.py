#input in python is a built-in function that allows you to take user input from the console. The input() function reads a line of text from the user and returns it as a string. You can also provide a prompt message to guide the user on what to input. 
# Here is an example of how to use the input() function in Python:
name = input("Enter your name: ")
print("Hello, " + name + "!")
age = int(input("Enter your age: "))
print("You are " + str(age) + " years old.")




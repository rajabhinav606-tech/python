#arithmetic operators are used to perform mathematical operations on numbers.
#  Here are some examples of arithmetic operators in Python: 
a = 10
b = 5

print("Addition:", a + b)        # Output: 15
print("Subtraction:", a - b)     # Output: 5
print("Multiplication:", a * b)  # Output: 50
print("Division:", a / b)        # Output: 2.0
print("Floor Division:", a // b) # Output: 2
print("Modulus:", a % b)        # Output: 0
print("Exponentiation:", a ** b) # Output: 100000

#comparison operators are used to compare two values and return a boolean result (True or False). 
# Here are some examples of comparison operators in Python:
x = 10
y = 20

print("Equal to:", x == y)       # Output: False
print("Not equal to:", x != y)   # Output: True
print("Greater than:", x > y)    # Output: False
print("Less than:", x < y)       # Output: True
print("Greater than or equal to:", x >= y) # Output: False
print("Less than or equal to:", x <= y)    # Output: True

#logical operators are used to combine multiple boolean expressions and return a boolean result.
#  Here are some examples of logical operators in Python:
p = True
q = False

print("Logical AND:", p and q)  # Output: False
print("Logical OR:", p or q)    # Output: True
print("Logical NOT:", not p)    # Output: False
print("Logical NOT:", not q)    # Output: True

#assignment operators are used to assign values to variables.
#  Here are some examples of assignment operators in Python:
c = 10
c += 5  # Equivalent to c = c + 5

print("After addition assignment:", c)  # Output: 15
c -= 3  # Equivalent to c = c - 3
print("After subtraction assignment:", c)  # Output: 12
c *= 2  # Equivalent to c = c * 2
print("After multiplication assignment:", c)  # Output: 24
c /= 4  # Equivalent to c = c / 4
print("After division assignment:", c)  # Output: 6.0
c //= 2  # Equivalent to c = c // 2
print("After floor division assignment:", c)  # Output: 3.0
c %= 2  # Equivalent to c = c % 2
print("After modulus assignment:", c)  # Output: 1.0
c **= 3  # Equivalent to c = c ** 3
print("After exponentiation assignment:", c)  # Output: 1.0


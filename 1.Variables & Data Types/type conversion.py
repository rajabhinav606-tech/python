# Explicit type conversion is the process of converting a value from one data type to another using built-in functions. Here are some examples of explicit type conversion in Python:
a = 10
b = 3.14

sum = float(a) + b #10.0 + 3.14 = 13.14
print("Sum:", sum) # Output: 13.14

# String to Integer is the process of converting a string that represents a number into an integer data type. In Python, you can use the int() function to perform this conversion. Here is an example:
str_num = "100"     
int_num = int(str_num)
print("Integer:", int_num) # Output: 100

# String to Float is the process of converting a string that represents a decimal number into a float data type. In Python, you can use the float() function to perform this conversion. Here is an example:
str_float = "3.14"
float_num = float(str_float)
print("Float:", float_num) # Output: 3.14

# Integer to String is the process of converting an integer data type into a string that represents the number. In Python, you can use the str() function to perform this conversion. Here is an example:
int_num = 100
str_num = str(int_num)
print("String:", str_num) # Output: "100"

# Float to String is the process of converting a float data type into a string that represents the decimal number. In Python, you can use the str() function to perform this conversion. Here is an example:
float_num = 3.14
str_float = str(float_num)
print("String:", str_float) # Output: "3.14"

#type casting is the process of converting a value from one data type to another using built-in functions. Here are some examples of type casting in Python:
a = 10
print(a)
b = float(a)
print(b)
